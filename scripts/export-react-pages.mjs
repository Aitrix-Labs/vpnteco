import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const siteDir = path.join(root, 'site')
const outFile = path.join(root, 'src', 'generated', 'pages.ts')

const pageFiles = [
  { file: 'index.html', route: '/', title: 'Vpnteco — Your Online Privacy, Fully Protected' },
  { file: 'features.html', route: '/features', title: 'Vpnteco — Features' },
  { file: 'about.html', route: '/about', title: 'Vpnteco — About Us' },
  { file: 'contact.html', route: '/contact', title: 'Vpnteco — Contact Us' },
  { file: 'pricing.html', route: '/pricing', title: 'Vpnteco — Pricing' },
  { file: 'blog.html', route: '/blog', title: 'Vpnteco — Blog' },
  { file: 'licenses.html', route: '/licenses', title: 'Vpnteco — Licenses' },
  { file: 'changelog.html', route: '/changelog', title: 'Vpnteco — Changelog' },
  { file: 'style-guide.html', route: '/style-guide', title: 'Vpnteco — Style Guide' },
  { file: 'signin.html', route: '/signin', title: 'Vpnteco — Sign In' },
  { file: 'signup.html', route: '/signup', title: 'Vpnteco — Sign Up' },
  { file: '401.html', route: '/401', title: 'Vpnteco — Password Protected' },
  { file: '404.html', route: '/404', title: 'Vpnteco — Page Not Found' },
]

function rewriteLinks(html) {
  return html
    .replaceAll('href="/vpnteco/features.html"', 'href="/vpnteco/features"')
    .replaceAll('href="/vpnteco/about.html"', 'href="/vpnteco/about"')
    .replaceAll('href="/vpnteco/contact.html"', 'href="/vpnteco/contact"')
    .replaceAll('href="/vpnteco/pricing.html"', 'href="/vpnteco/pricing"')
    .replaceAll('href="/vpnteco/blog.html"', 'href="/vpnteco/blog"')
    .replaceAll('href="/vpnteco/licenses.html"', 'href="/vpnteco/licenses"')
    .replaceAll('href="/vpnteco/changelog.html"', 'href="/vpnteco/changelog"')
    .replaceAll('href="/vpnteco/style-guide.html"', 'href="/vpnteco/style-guide"')
    .replaceAll('href="/vpnteco/signin.html"', 'href="/vpnteco/signin"')
    .replaceAll('href="/vpnteco/signup.html"', 'href="/vpnteco/signup"')
    .replaceAll('href="/vpnteco/401.html"', 'href="/vpnteco/401"')
    .replaceAll('href="/vpnteco/404.html"', 'href="/vpnteco/404"')
    .replaceAll('href="/vpnteco/index.html"', 'href="/vpnteco/"')
}

function extract(html) {
  const pageMatch = html.match(/data-wf-page="([^"]+)"/)
  const siteMatch = html.match(/data-wf-site="([^"]+)"/)
  const styles = [...html.matchAll(/<style[^>]*>[\s\S]*?<\/style>/gi)].map((m) => m[0]).join('\n')
  let body = html.match(/<body[^>]*>([\s\S]*)<\/body>/i)?.[1] ?? ''
  // Drop page scripts; React shell loads shared scripts once
  body = body.replace(/<script[\s\S]*?<\/script>/gi, '')
  body = rewriteLinks(body)
  return {
    wfPage: pageMatch?.[1] ?? '',
    wfSite: siteMatch?.[1] ?? '6ab7f78a9781541f26e39f0f',
    styles,
    body: body.trim(),
  }
}

const pages = []
for (const page of pageFiles) {
  const full = path.join(siteDir, page.file)
  if (!fs.existsSync(full)) {
    console.warn('missing', page.file)
    continue
  }
  const raw = fs.readFileSync(full, 'utf8')
  const extracted = extract(raw)
  pages.push({
    route: page.route,
    title: page.title,
    ...extracted,
  })
  console.log('exported', page.route)
}

fs.mkdirSync(path.dirname(outFile), { recursive: true })

const serialized = pages
  .map((page) => {
    return `  {
    route: ${JSON.stringify(page.route)},
    title: ${JSON.stringify(page.title)},
    wfPage: ${JSON.stringify(page.wfPage)},
    wfSite: ${JSON.stringify(page.wfSite)},
    styles: ${JSON.stringify(page.styles)},
    body: ${JSON.stringify(page.body)},
  }`
  })
  .join(',\n')

const contents = `/* Auto-generated by scripts/export-react-pages.mjs — do not edit */
export type VpntecoPage = {
  route: string
  title: string
  wfPage: string
  wfSite: string
  styles: string
  body: string
}

export const pages: VpntecoPage[] = [
${serialized}
]

export function findPage(pathname: string): VpntecoPage {
  const clean = pathname.replace(/\\/$/, '') || '/'
  return pages.find((page) => page.route === clean || page.route === pathname) ?? pages.find((page) => page.route === '/404')!
}
`

fs.writeFileSync(outFile, contents)
console.log('wrote', path.relative(root, outFile), `(${pages.length} pages)`)
